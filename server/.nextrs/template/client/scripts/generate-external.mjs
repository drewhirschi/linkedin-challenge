// Publish the browser extension's React-free typed client.
//
// `cargo nextrs client generate` runs this from the generated client package (.nextrs/client)
// whenever nextrs.client.json is present. The npm scripts themselves live at the app root — the
// generated package is a build product and owns no workflow — so every command here runs from
// there, and only the orval invocation is re-run with the external base URL set.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const clientDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// .nextrs/client -> .nextrs -> the app root that owns package.json and the scripts.
const appDir = resolve(clientDir, "..", "..");
const configPath = resolve(clientDir, process.argv[2] ?? "nextrs.client.json");
const marker = ".nextrs-generated-client";

if (!existsSync(configPath)) {
  fail(`missing config: ${configPath}\nCopy nextrs.client.example.json and set an explicit output path.`);
}

const config = JSON.parse(readFileSync(configPath, "utf8"));
if (typeof config.output !== "string" || config.output.trim() === "") {
  fail('config must contain a non-empty "output" path');
}
if (typeof config.baseUrl !== "string") {
  fail('config must contain a string "baseUrl" (use "" for same-origin)');
}

const outputDir = isAbsolute(config.output)
  ? resolve(config.output)
  : resolve(clientDir, config.output);
guardOutput(outputDir);
assertOutputCleanable(outputDir);

// The in-app client is produced exactly as an ordinary generation would produce it; the extension
// build is an extra orval target layered on the same OpenAPI document.
run("npm", ["run", "client:ensure"]);
run("npm", ["run", "client:dump"]);
run("npm", ["run", "client:orval"], {
  ...process.env,
  NEXTRS_EXTERNAL_CLIENT_BASE_URL: config.baseUrl,
});
// Orval's `clean: true` wipes src/generated/, including the barrel index.ts files that the nextrs
// build step writes. The barrels must be rebuilt before tsc, or both package entry points fail to
// resolve ./generated/fetch and ./generated/react-query. This mirrors the root client:generate.
run("cargo", ["build"]);
run("npm", ["run", "client:build"]);
run("npx", ["tsc", "-p", resolve(clientDir, "tsconfig.external.json")]);

const buildDir = resolve(clientDir, "external-dist");
if (!existsSync(resolve(buildDir, "client.js")) || !existsSync(resolve(buildDir, "client.d.ts"))) {
  fail("external client build did not produce client.js and client.d.ts");
}

prepareOutput(outputDir);
cpSync(buildDir, outputDir, { recursive: true });
writeFileSync(resolve(outputDir, marker), "Generated by nextrs. Safe to replace.\n");
writeFileSync(
  resolve(outputDir, "package.json"),
  `${JSON.stringify({ type: "module", exports: { ".": { types: "./client.d.ts", import: "./client.js" } } }, null, 2)}\n`,
);
console.log(`published external client to ${outputDir}`);

function prepareOutput(dir) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    return;
  }
  const entries = readdirSync(dir);
  for (const entry of entries) {
    rmSync(resolve(dir, entry), { recursive: true, force: true });
  }
}

function assertOutputCleanable(dir) {
  if (!existsSync(dir)) return;
  const entries = readdirSync(dir);
  if (entries.length > 0 && !entries.includes(marker)) {
    fail(`refusing to clean unmarked, non-empty output directory: ${dir}`);
  }
}

function guardOutput(dir) {
  const rel = relative(appDir, dir);
  if (dir === appDir || dir === clientDir || dir === resolve(appDir, "..") || dir === "/") {
    fail(`refusing unsafe output directory: ${dir}`);
  }
  if (rel === "") fail(`output must be a dedicated generated directory: ${dir}`);
}

function run(command, args, env = process.env) {
  const result = spawnSync(command, args, { cwd: appDir, env, stdio: "inherit" });
  if (result.error) fail(`${command} failed: ${result.error.message}`);
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function fail(message) {
  console.error(`nextrs external client: ${message}`);
  process.exit(1);
}
